#!/usr/bin/env node
// Ported from bow-decision-challenges tools/boss/hooks/protect-run-state.mjs @ 9313c91.
// Independent-review repair: while any Boss run is active, direct edits to the
// harness constitution (.boss/config, .boss/schemas) are also denied — the
// config-integrity gate check is the deterministic backstop, this hook stops
// the accident earlier. Between runs, constitution evolution stays possible.
import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";

let raw = "";
for await (const chunk of process.stdin) raw += chunk;

function anyActiveRun(repoRoot) {
  const runsDir = path.join(repoRoot, ".boss", "runs");
  if (!existsSync(runsDir)) return false;
  for (const entry of readdirSync(runsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith(".")) continue;
    try {
      const state = JSON.parse(readFileSync(path.join(runsDir, entry.name, "state.json"), "utf8"));
      if (state.status === "active") return true;
    } catch {
      // An unreadable projection is not a reason to block unrelated edits.
    }
  }
  return false;
}

function deny(reason) {
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: reason,
    },
  }));
}

try {
  const input = JSON.parse(raw || "{}");
  const toolInput = input.tool_input ?? input.toolInput ?? {};
  const filePath = String(toolInput.file_path ?? toolInput.path ?? "").replaceAll("\\", "/");
  const protectedRunFile = /\.boss\/runs\/[^/]+\/(events\.jsonl|state\.json|SUMMARY\.md|contract\.md)$/.test(filePath);
  if (protectedRunFile) {
    deny("BOW Boss run history and projections are runtime-managed. Use npm run boss -- ...; do not edit this file directly.");
  } else {
    const constitutionMatch = filePath.match(/^(.*?)\.boss\/(config|schemas)\//);
    if (constitutionMatch) {
      const repoRoot = constitutionMatch[1] === "" ? process.cwd() : constitutionMatch[1];
      if (anyActiveRun(repoRoot)) {
        deny("The harness constitution (.boss/config, .boss/schemas) is frozen while a Boss run is active; a mid-run change would also fail the config-integrity gate. Close the run, or have the founder record an override on subject config-change first.");
      }
    }
  }
} catch {
  // A guard must not break ordinary work when a host changes its hook envelope.
}
